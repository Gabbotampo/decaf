#!/usr/bin/env python3
"""Vendor the Java runtime into the native mod, which is one crate.

A Horizon native mod is one flat crate (docs/modding/src/how-to/native-mods/016-the-mods-crate.md):
the launcher stages a single crate and refuses path dependencies, so the bytecode runtime that
``mod/`` runs is copied into it instead of being linked. This tool is the one place that copy is
made, so the mod never drifts from ``crates/horizon-native-java``:

* it copies every ``.rs`` file of ``crates/horizon-native-java/src`` except ``main.rs`` (the
  command-line probe, which the mod does not use) into ``mod/src/runtime/``;
* each data file a vendored source embeds with ``include_str!("…")``/``include_bytes!("…")``
  (a generated table, a test oracle's JSON) goes beside it so the vendored module still finds it.
  The path must be a string literal inside ``src``: anything else is an error, never a silently
  missing file. How it goes depends on whether a Sunrise package carries it:

  * a ``.toml`` under ``src/`` is package source, so it is copied byte for byte;
  * any other file (``.txt``, ``.tsv``, ``.json``, binary) is not: a native package carries only
    ``Cargo.toml``, ``Cargo.lock``, ``build.rs``, the root notices and the ``.rs``/``.toml`` files
    under ``src/`` (Sunrise's ``mod_source::package::source_file``), and the native build and
    ``cargo sunrise-mod check`` compile the packed files only. Sunrise's documented way to embed a
    code-only table is Rust source under ``src/`` (docs/modding/src/how-to/native-mods/
    03-data-files.md, "Embedded data"), so the file is written as ``<name>.rs`` beside it.
    Sunrise's uses scan parses every packed ``.rs`` as a file of items, so that file is one item,
    ``pub(crate) const VENDORED_DATA: &str = "…";`` holding exactly the file's bytes (``&[u8; N]``
    and a byte string for ``include_bytes!``). ``runtime/mod.rs`` declares it, at its end, as the
    module ``vendored_<name>`` (``#[path = "<name>.rs"]``, which the uses scan follows), and the
    vendored call becomes ``crate::runtime::vendored_<name>::VENDORED_DATA``: the same
    ``&'static str`` (or ``&'static [u8; N]``) the macro gave, valid in any position it stood
    (a ``const``, a test module, a nested module). An ``include!`` cannot stand in for it: in an
    expression it reads an expression file, which the uses scan refuses, and in a block it is
    refused;
* ``lib.rs`` becomes ``runtime/mod.rs``, the module the mod's ``src/lib.rs`` declares;
* each ``crate::`` path is rewritten to ``crate::runtime::``, because the runtime is no longer a
  crate root but a module of the mod's crate. Relative paths (``super::``, ``self::``) and the
  ``#[path]`` submodules of ``client_surface.rs`` need no change.

The vendored files are committed: a clean clone builds the mod without running this tool.

There is one check, ``--check``: it regenerates the copy in memory from
``crates/horizon-native-java/src`` **as it is now** and compares it byte for byte with the committed
``mod/src/runtime/``. Every file must match, none may be missing, and nothing else may sit in the
copy. That one comparison catches both ways the copy can go wrong:

* a hand edit to ``mod/src/runtime/`` (the regenerated bytes differ from the committed ones);
* a runtime change that was not re-vendored (likewise), including a changed embedded data file.

CI runs it on every pull request and every push (``.github/workflows/ci.yml``), and every commit that
touches the runtime re-vendors in the same commit, so the mod always carries the runtime's current
behaviour.

(The copy used to be pinned by a ``mod/vendor.lock`` of per-file SHA-256 hashes and a source commit.
It changed in nearly every runtime PR, so any two runtime PRs conflicted on it; and it guarded nothing
the regenerate-and-compare check above does not, so it is gone.)

    python3 tools/vendor.py          # write (or refresh) mod/src/runtime
    python3 tools/vendor.py --check  # fail unless mod/src/runtime is exactly what that writes
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path, PurePosixPath

# The crate the runtime comes from, and the mod that carries a copy of it.
RUNTIME_SRC = Path("crates/horizon-native-java/src")
MOD = Path("mod")
VENDOR = MOD / "src" / "runtime"
# `main.rs` is the command-line probe: neither a module of the library nor anything the mod calls.
SKIP = {PurePosixPath("main.rs")}
# The crate-root path a vendored file's `crate::` becomes.
PREFIX = "crate::runtime::"
# The runtime keeps one item for every capability the probe, the corpus tools and the weaver use;
# a mod calls a handful. Its warnings are the crate's, not the mod's, so the vendored root module
# silences the two that the whole-crate copy necessarily raises.
ROOT_HEADER = "// @generated by tools/vendor.py from crates/horizon-native-java/src; do not edit.\n#![allow(dead_code, unused_imports)]\n\n"
# `include_str!("path")` / `include_bytes!("path")`, with the macro kind and the literal path
# captured; and any use of the two macros at all, so one whose argument is not a plain literal is
# refused, not skipped.
INCLUDE_LITERAL = re.compile(rb'\binclude_(str|bytes)!\(\s*"([^"\\]+)"\s*\)')
INCLUDE_ANY = re.compile(rb"\binclude_(?:str|bytes)!\(")
# What a Sunrise native package carries under `src/` besides `.rs` source
# (`mod_source::package::source_file` at the pinned build): an embedded file of this kind is copied
# as it is; any other is embedded as Rust source.
PACKAGED_DATA = {".toml"}
# The bidirectional-text controls rustc's `text_direction_codepoint_in_literal` lint denies in a
# string literal, written as escapes instead.
BIDI_CONTROLS = frozenset("\u202a\u202b\u202c\u202d\u202e\u2066\u2067\u2068\u2069")
# The first line of an embedded data file's Rust form, the one item it declares, and the prefix of
# the module `runtime/mod.rs` declares it as.
EMBED_HEADER = "// @generated by tools/vendor.py from {source}: its exact {what}; do not edit.\n"
EMBED_CONST = "VENDORED_DATA"
EMBED_MODULE_PREFIX = "vendored_"
# What `runtime/mod.rs` ends with when the runtime embeds unpackaged data files.
EMBED_MODULES_HEADER = (
    "\n// Data files the runtime embeds, as the Rust source a Sunrise package carries"
    " (tools/vendor.py).\n"
)


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def vendored_name(relative: PurePosixPath) -> PurePosixPath:
    """Where one source file goes in `mod/src/runtime/`."""
    return PurePosixPath("mod.rs") if relative == PurePosixPath("lib.rs") else relative


def included_files(src: Path, path: Path, original: bytes) -> list[tuple[str, PurePosixPath]]:
    """The data files one source embeds, relative to `src`, each with its macro kind
    (`"str"` or `"bytes"`).

    `include_str!`/`include_bytes!` resolve their path against the including file's directory,
    which the vendored copy keeps, so each file goes to the same relative place. A macro whose
    argument is not a plain string literal, or a path that leaves `src`, cannot be vendored and
    stops the tool: the mod's build would otherwise fail on a file nobody vendored.
    """
    literal = INCLUDE_LITERAL.findall(original)
    if len(literal) != len(INCLUDE_ANY.findall(original)):
        raise SystemExit(f"{path}: include_str!/include_bytes! of a non-literal path cannot be vendored")
    out = []
    for kind, raw in literal:
        target = (path.parent / raw.decode("utf-8")).resolve()
        try:
            relative = target.relative_to(src.resolve())
        except ValueError:
            raise SystemExit(f"{path}: includes {raw.decode()}, outside {RUNTIME_SRC}") from None
        if not target.is_file():
            raise SystemExit(f"{path}: includes {raw.decode()}, which does not exist")
        out.append((kind.decode(), PurePosixPath(relative.as_posix())))
    return out


def packaged(relative: PurePosixPath) -> bool:
    """Whether a Sunrise native package carries this file under `src/` as it is."""
    return relative.suffix in PACKAGED_DATA


def embedded_name(relative: PurePosixPath) -> PurePosixPath:
    """The Rust source an unpackaged data file is embedded as: `table.txt` -> `table.txt.rs`."""
    return relative.with_name(relative.name + ".rs")


def rust_str_literal(text: str) -> str:
    """`text` as one Rust string literal that evaluates to exactly `text`.

    Lines stay lines (a literal newline inside the quotes is a newline of the value), so the
    embedded table still reads and diffs as its source does. A backslash and a quote are
    escaped; a carriage return and every other control character are written as escapes, since
    rustc normalises a CRLF in source to LF and refuses a bare CR in a literal, and so are the
    bidirectional-text controls rustc denies in a literal (`text_direction_codepoint_in_literal`).
    Everything else, non-ASCII included, is the source's own UTF-8.
    """
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch in "\n\t":
            out.append(ch)
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F or ch in BIDI_CONTROLS:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def rust_bytes_literal(data: bytes) -> str:
    """`data` as one Rust byte string literal that evaluates to exactly `data`: printable ASCII
    and newlines as themselves, every other byte as `\\xNN`."""
    out = ['b"']
    for byte in data:
        if byte == 0x5C:
            out.append("\\\\")
        elif byte == 0x22:
            out.append('\\"')
        elif byte == 0x0A or 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02x}")
    out.append('"')
    return "".join(out)


def embedded_source(relative: PurePosixPath, kind: str, content: bytes) -> bytes:
    """The Rust source that stands for `relative` in place of `include_str!`/`include_bytes!`:
    a file with one item, the `EMBED_CONST` holding the file's exact contents with the type the
    macro gives (`&str`, or `&[u8; N]`)."""
    source = RUNTIME_SRC / relative
    if kind == "str":
        try:
            text = content.decode("utf-8")
        except UnicodeDecodeError:
            raise SystemExit(f"{source}: include_str! of a file that is not UTF-8") from None
        item = f"pub(crate) const {EMBED_CONST}: &str = {rust_str_literal(text)};"
        what = "text"
    else:
        item = (
            f"pub(crate) const {EMBED_CONST}: &[u8; {len(content)}] = "
            f"{rust_bytes_literal(content)};"
        )
        what = "bytes"
    return (EMBED_HEADER.format(source=source.as_posix(), what=what) + item + "\n").encode("utf-8")


def embedded_module(relative: PurePosixPath) -> str:
    """The module `runtime/mod.rs` declares an embedded file's Rust form as: `tables/a-b.txt` is
    `vendored_tables_a_b_txt`."""
    return EMBED_MODULE_PREFIX + re.sub(r"[^0-9a-z]", "_", relative.as_posix().lower())


def embedded_value(relative: PurePosixPath) -> bytes:
    """The path a rewritten call reads an embedded file's value by, from anywhere in the crate.

    Written with the runtime's own `crate::` root, as every other path of its source: the
    vendoring moves it under `runtime` with the rest."""
    return f"crate::{embedded_module(relative)}::{EMBED_CONST}".encode()


def embedded_modules(embedded: list[PurePosixPath]) -> str:
    """What `runtime/mod.rs` ends with: one `#[path]` module per embedded file's Rust form."""
    if not embedded:
        return ""
    lines = [EMBED_MODULES_HEADER]
    for relative in embedded:
        lines.append(f'#[path = "{embedded_name(relative).as_posix()}"]\n')
        lines.append(f"mod {embedded_module(relative)};\n")
    return "".join(lines)


def rewrite_includes(text: bytes, included: list[tuple[str, PurePosixPath]]) -> bytes:
    """Each `include_str!`/`include_bytes!` of a file the package does not carry, as a read of
    that file's Rust form. `included` is what `included_files` found in `text`, in order."""
    resolved = iter(included)

    def replace(match: re.Match[bytes]) -> bytes:
        _, relative = next(resolved)
        if packaged(relative):
            return match.group(0)
        return embedded_value(relative)

    return INCLUDE_LITERAL.sub(replace, text)


def vendored_files_on_disk(root: Path) -> set[str]:
    """Every file under `mod/src/runtime/`: sources and the data files they embed."""
    target = root / VENDOR
    if not target.is_dir():
        return set()
    return {path.relative_to(target).as_posix() for path in target.rglob("*") if path.is_file()}


def expected(root: Path) -> dict[str, tuple[bytes, bytes]]:
    """Every file the vendoring produces: {destination path: (source bytes, vendored bytes)}.

    A packaged data file a source embeds is vendored unchanged (source bytes == vendored bytes);
    any other is vendored as its Rust form (`embedded_source`) under `embedded_name`.
    """
    src = root / RUNTIME_SRC
    files = {}
    data: dict[PurePosixPath, str] = {}
    for path in sorted(src.rglob("*.rs")):
        relative = PurePosixPath(path.relative_to(src).as_posix())
        if relative in SKIP:
            continue
        original = path.read_bytes()
        included = included_files(src, path, original)
        for kind, relative_data in included:
            if data.setdefault(relative_data, kind) != kind:
                raise SystemExit(
                    f"{RUNTIME_SRC / relative_data}: embedded as both text and bytes; "
                    "its Rust form can only be one of them"
                )
        # The runtime stops being a crate root: its own paths move under the mod's `runtime`
        # module. Token-level enough: `crate::` is a path qualifier in this tree and never
        # appears inside a string or a character literal (checked by the test that reads it).
        text = rewrite_includes(original, included).decode("utf-8").replace("crate::", PREFIX)
        destination = vendored_name(relative)
        if destination == PurePosixPath("mod.rs"):
            text = ROOT_HEADER + text
        files[str(destination)] = (original, text.encode("utf-8"))
    embedded = []
    modules: dict[str, PurePosixPath] = {}
    for relative, kind in sorted(data.items()):
        if relative.suffix == ".rs":
            raise SystemExit(f"{RUNTIME_SRC / relative}: an included .rs file would be rewritten")
        content = (src / relative).read_bytes()
        if packaged(relative):
            files[str(relative)] = (content, content)
            continue
        name = embedded_name(relative)
        if (src / name).exists() or str(name) in files:
            raise SystemExit(f"{RUNTIME_SRC / relative}: its Rust form {name} is already a source file")
        other = modules.setdefault(embedded_module(relative), relative)
        if other != relative:
            raise SystemExit(
                f"{RUNTIME_SRC / relative} and {RUNTIME_SRC / other} would be one module, "
                f"{embedded_module(relative)}"
            )
        files[str(name)] = (content, embedded_source(relative, kind, content))
        embedded.append(relative)
    if embedded:
        # The modules go at the end of the root module, after its inner attributes and items.
        source, vendored = files["mod.rs"]
        files["mod.rs"] = (source, vendored + embedded_modules(embedded).encode("utf-8"))
    return files


def drift(root: Path) -> list[str]:
    """Every difference between the committed copy and what the runtime source vendors to now.

    Byte for byte, file by file: a hand edit to `mod/src/runtime/`, a runtime change nobody
    re-vendored, a vendored file whose source is gone and a missing copy all show up here.
    """
    problems = []
    files = expected(root)
    target = root / VENDOR
    for name, (_, vendored_bytes) in sorted(files.items()):
        path = target / name
        source = RUNTIME_SRC / ("lib.rs" if name == "mod.rs" else name)
        if not path.is_file():
            problems.append(f"{VENDOR / name}: missing (vendored from {source})")
        elif path.read_bytes() != vendored_bytes:
            problems.append(
                f"{VENDOR / name}: differs from what {source} vendors to "
                "(edited by hand, or the runtime changed and was not re-vendored)"
            )
    for name in sorted(vendored_files_on_disk(root) - set(files)):
        problems.append(f"{VENDOR / name}: vendored file has no source in {RUNTIME_SRC}")
    return problems


def write(root: Path) -> None:
    files = expected(root)
    target = root / VENDOR
    target.mkdir(parents=True, exist_ok=True)
    for name, (_, vendored_bytes) in sorted(files.items()):
        destination = target / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(vendored_bytes)
    # A file whose source is gone (or that no source embeds any more) stops being part of the mod.
    for name in vendored_files_on_disk(root) - set(files):
        (target / name).unlink()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail unless mod/src/runtime is exactly what the runtime source vendors to now",
    )
    parser.add_argument("--repo", type=Path, default=None, help="the tree to vendor (default: this one)")
    args = parser.parse_args(argv)
    root = (args.repo or repo_root()).resolve()
    if args.check:
        problems = drift(root)
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        if problems:
            print(
                f"{len(problems)} vendored file(s) are not what tools/vendor.py produces; "
                "run python3 tools/vendor.py and commit mod/src/runtime",
                file=sys.stderr,
            )
            return 1
        print(f"{len(expected(root))} vendored file(s) match {RUNTIME_SRC}")
        return 0
    write(root)
    print(f"vendored {len(expected(root))} file(s) into {VENDOR}")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
