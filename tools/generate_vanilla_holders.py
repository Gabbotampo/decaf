#!/usr/bin/env python3
"""Generate 26.3 vanilla holder field/id/order facts from javap output."""
from pathlib import Path
import argparse, re

def parse(path: Path):
    text = path.read_text()
    text = text[text.index("static {};"):]
    rows = []
    first = None
    for line in text.splitlines():
        match = re.search(r"// String (.+)$", line)
        if match and first is None:
            first = match.group(1)
        match = re.search(r"// Field ([A-Z0-9_]+):", line)
        if match:
            if first is None:
                raise SystemExit(f"{path}: no preceding string for {match.group(1)}")
            rows.append((match.group(1), first))
            first = None
    if len(rows) != 40 or len({field for field, _ in rows}) != 40:
        raise SystemExit(f"{path}: expected 40 distinct holder rows, got {len(rows)}")
    return rows

def render(args):
    attrs, effects = parse(args.attributes), parse(args.mob_effects)
    out = [
        "//! @generated by tools/generate_vanilla_holders.py from the real 26.3 javap output.",
        "//! Regenerate with:",
        "//! javap -classpath <server-game.jar> -p -c net.minecraft.world.entity.ai.attributes.Attributes > /tmp/Attributes.javap",
        "//! javap -classpath <server-game.jar> -p -c net.minecraft.world.effect.MobEffects > /tmp/MobEffects.javap",
        "//! python3 tools/generate_vanilla_holders.py --attributes /tmp/Attributes.javap --mob-effects /tmp/MobEffects.javap --output crates/horizon-native-java/src/vanilla_holders_table.rs",
        "",
        "pub(crate) const ATTRIBUTE_FIELDS: &[(&str, &str, usize)] = &[",
    ]
    out += [f'    ("{f}", "minecraft:{i}", {n}),' for n, (f, i) in enumerate(attrs)]
    out += ["];"]
    out += ["", "pub(crate) const MOB_EFFECT_FIELDS: &[(&str, &str, usize)] = &["]
    out += [f'    ("{f}", "minecraft:{i}", {n}),' for n, (f, i) in enumerate(effects)]
    out += ["];", ""]
    args.output.write_text("\n".join(out))

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--attributes", type=Path, required=True)
    p.add_argument("--mob-effects", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    render(p.parse_args())

if __name__ == "__main__": main()
