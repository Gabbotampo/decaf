#!/usr/bin/env python3
"""Record which game classes a real Fabric 26.3 dedicated server loads before any mod runs.

Writes `crates/horizon-native-java/src/fabric_server_bootstrap_classes_26_3.txt`: the
internal names of every class from the Minecraft server jar that the JVM loads before
the first `main` entrypoint (`ModInitializer`) class, one per line, sorted.

Why the runtime needs it
------------------------
A `required` Mixin config whose mixin real Mixin rejects (`InvalidMixinException`)
fails its target's class load: Mixin rethrows, and Fabric's Knot throws
`RuntimeException: Mixin transformation of <target> failed` from that load. When the
target is a game class the game itself loads before mods initialise (`Player`, `Level`,
...), the game never reaches a mod's code, so the jar's code is refused as a whole. Any
other failed class is counted where the jar's code first uses it. That split is decided
by this list, measured rather than guessed.

How it is measured
------------------
The server runs under `-Xlog:class+load` with fabric-loader on the class path
(`KnotServer`), the vanilla libraries, sponge-mixin, and a one-class probe mod whose
`onInitialize` only prints. Every game class load is logged with its source jar; the
probe's own `probe.Init` load marks the point Fabric starts the `main` entrypoints. The
server then runs to `Done` and is stopped. Every game class goes through Mixin's
transformer: `MixinProcessor` is loaded before the first `net.minecraft` class.

Reproducing the committed file byte-for-byte
--------------------------------------------
    python3 tools/trace_fabric_bootstrap_classes.py \\
        --server-jar <unbundled Minecraft 26.3 server jar> \\
        --libs <directory holding fabric-loader 0.20.1, sponge-mixin 0.17.5+mixin.0.8.7,
                ASM 9.8 and the 26.3 server libraries> \\
        --jdk <JDK 25 home, e.g. Temurin 25.0.5+8> \\
        --output crates/horizon-native-java/src/fabric_server_bootstrap_classes_26_3.txt

The inputs are checked before the server runs, and anything else is refused: the server
jar's `version.json` names 26.3, the libraries hold exactly one `fabric-loader-0.20.1.jar`
and one `sponge-mixin-0.17.5+mixin.0.8.7.jar` (and no other loader or Mixin), the JDK is
25, and the server jar's and every library's file name and SHA-256, and the JDK's
`java.runtime.version`, equal the manifest recorded in the output's header (`# input`
lines; names and hashes only). `--record` writes a new manifest instead, for a deliberate
change of inputs. The server jar of the committed file is the one Mojang's 26.3 bundler
lists (`META-INF/versions.list`: `26.3/server-26.3.jar`, the same SHA-256).

The server jar is the one the 26.3 bundler unpacks (`versions/26.3/server-26.3.jar`),
not the bundler itself. The world and `server.properties` do not change the list: no
world or property is read before the first entrypoint (a second run with a default
world gives the same file).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

HEADER = """\
# Game classes a real Fabric 26.3 dedicated server loads before the first `main` entrypoint.
# Minecraft 26.3 server, fabric-loader 0.20.1, sponge-mixin 0.17.5+mixin.0.8.7, JDK 25, no
# other mods. Generated by tools/trace_fabric_bootstrap_classes.py (-Xlog:class+load); do not
# edit by hand. The `# input` lines are the exact inputs (names and SHA-256), which the tool
# checks before every run. Then one internal class name per line, sorted.
"""

PROBE_SOURCE = """\
package probe;

public class Init implements net.fabricmc.api.ModInitializer {
    @Override
    public void onInitialize() {
        System.out.println("PROBE-MODINIT-BEGIN");
        System.out.flush();
    }
}
"""

PROBE_MOD_JSON = (
    '{"schemaVersion":1,"id":"probe","version":"1.0.0","environment":"*",'
    '"entrypoints":{"main":["probe.Init"]}}'
)

SERVER_PROPERTIES = """\
online-mode=false
server-port=25999
view-distance=2
simulation-distance=2
"""

LOAD_LINE = re.compile(r"\[class,load\] (\S+) source: (.*)$")

# The versions the header claims; anything else is refused before the server runs.
LOADER_JAR = "fabric-loader-0.20.1.jar"
MIXIN_JAR = "sponge-mixin-0.17.5+mixin.0.8.7.jar"
GAME_VERSION = "26.3"
JDK_FEATURE = "25"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def jdk_runtime_version(jdk: Path) -> str:
    """`java.runtime.version` of the JDK at `jdk`."""
    result = subprocess.run(
        [str(jdk / "bin" / "java"), "-XshowSettings:properties", "-version"],
        capture_output=True,
        text=True,
        check=True,
    )
    for line in result.stderr.splitlines():
        key, _, value = line.strip().partition(" = ")
        if key == "java.runtime.version":
            return value
    raise SystemExit(f"no java.runtime.version from {jdk}")


def input_manifest(server_jar: Path, libs: list[Path], jdk: Path) -> list[str]:
    """The trace's inputs as `# input` header lines (names and hashes, no paths), after
    checking the versions this file's header claims."""
    with zipfile.ZipFile(server_jar) as archive:
        if "META-INF/versions.list" in archive.namelist():
            raise SystemExit(f"{server_jar.name} is the server bundler; pass the server jar it unpacks")
        try:
            version = json.loads(archive.read("version.json"))["id"]
        except KeyError:
            raise SystemExit(f"{server_jar.name} has no version.json: not an unbundled server jar")
    if version != GAME_VERSION:
        raise SystemExit(f"{server_jar.name} is Minecraft {version}, not {GAME_VERSION}")
    names = [lib.name for lib in libs]
    if len(set(names)) != len(names):
        raise SystemExit("two libraries share a file name")
    for prefix, wanted in (("fabric-loader-", LOADER_JAR), ("sponge-mixin-", MIXIN_JAR)):
        found = [name for name in names if name.startswith(prefix)]
        if found != [wanted]:
            raise SystemExit(f"expected exactly {wanted} among the libraries, found {found}")
    runtime = jdk_runtime_version(jdk)
    if runtime.split(".")[0].split("+")[0] != JDK_FEATURE:
        raise SystemExit(f"JDK {runtime} is not JDK {JDK_FEATURE}")
    lines = [f"# input jdk {runtime}", f"# input server {server_jar.name} sha256:{sha256(server_jar)}"]
    lines += [f"# input library {lib.name} sha256:{sha256(lib)}" for lib in sorted(libs, key=lambda lib: lib.name)]
    return lines


def recorded_manifest(output: Path) -> list[str] | None:
    """The `# input` lines of an existing output, or `None` when there is none yet."""
    if not output.is_file():
        return None
    return [line for line in output.read_text(encoding="utf-8").splitlines() if line.startswith("# input ")]


def build_probe(jdk: Path, loader: Path, work: Path) -> Path:
    """Compile the probe mod and pack it as `mods/probe.jar` under `work/run`."""
    src = work / "src" / "probe"
    classes = work / "classes"
    src.mkdir(parents=True)
    classes.mkdir()
    (src / "Init.java").write_text(PROBE_SOURCE, encoding="utf-8")
    subprocess.run(
        [str(jdk / "bin" / "javac"), "-cp", str(loader), "-d", str(classes), str(src / "Init.java")],
        check=True,
    )
    (classes / "fabric.mod.json").write_text(PROBE_MOD_JSON, encoding="utf-8")
    mods = work / "run" / "mods"
    mods.mkdir(parents=True)
    jar = mods / "probe.jar"
    subprocess.run([str(jdk / "bin" / "jar"), "--create", "--file", str(jar), "-C", str(classes), "."], check=True)
    return jar


def run_server(jdk: Path, server_jar: Path, libs: list[Path], run: Path, timeout: int) -> list[str]:
    """Run the server to `Done`, stop it, and return its interleaved log and class-load trace."""
    (run / "eula.txt").write_text("eula=true\n", encoding="utf-8")
    (run / "server.properties").write_text(SERVER_PROPERTIES, encoding="utf-8")
    command = [
        str(jdk / "bin" / "java"),
        "-Xmx2G",
        "-Xlog:class+load=info:stdout:uptime,tags",
        f"-Dfabric.gameJarPath={server_jar}",
        "-cp",
        ":".join(str(lib) for lib in libs),
        "net.fabricmc.loader.impl.launch.knot.KnotServer",
        "nogui",
    ]
    process = subprocess.Popen(
        command, cwd=run, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    assert process.stdin is not None and process.stdout is not None
    lines: list[str] = []
    start = time.monotonic()
    stopping = False
    for line in process.stdout:
        lines.append(line.rstrip("\n"))
        if not stopping and "Done (" in line:
            process.stdin.write("stop\n")
            process.stdin.flush()
            stopping = True
        if time.monotonic() - start > timeout:
            process.kill()
            raise SystemExit(f"server did not finish within {timeout}s")
    if process.wait() != 0:
        raise SystemExit(f"server exited with {process.returncode}")
    if not stopping:
        raise SystemExit("server stopped before reaching Done")
    return lines


def bootstrap_classes(lines: list[str], server_jar: Path) -> list[str]:
    """Game classes (from `server_jar`) loaded before the probe's entrypoint class."""
    source = f"file:{server_jar}"
    loaded: set[str] = set()
    for line in lines:
        match = LOAD_LINE.search(line)
        if not match:
            continue
        name, origin = match.groups()
        if name == "probe.Init":
            return sorted(name.replace(".", "/") for name in loaded)
        if origin == source:
            loaded.add(name)
    raise SystemExit("the probe entrypoint never loaded")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--server-jar", type=Path, required=True)
    parser.add_argument("--libs", type=Path, required=True)
    parser.add_argument("--jdk", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--timeout", type=int, default=600)
    parser.add_argument(
        "--record",
        action="store_true",
        help="write a new input manifest instead of requiring the recorded one",
    )
    args = parser.parse_args()
    server_jar = args.server_jar.resolve()
    libs = sorted(path.resolve() for path in args.libs.rglob("*.jar"))
    manifest = input_manifest(server_jar, libs, args.jdk)
    recorded = recorded_manifest(args.output)
    if not args.record:
        if not recorded:
            raise SystemExit(f"{args.output} records no input manifest; pass --record to write one")
        if recorded != manifest:
            missing = sorted(set(recorded) - set(manifest))
            extra = sorted(set(manifest) - set(recorded))
            raise SystemExit(
                "the inputs differ from the recorded manifest:\n"
                + "".join(f"  recorded, not given: {line[2:]}\n" for line in missing)
                + "".join(f"  given, not recorded: {line[2:]}\n" for line in extra)
            )
    loader = next(lib for lib in libs if lib.name == LOADER_JAR)
    with tempfile.TemporaryDirectory(prefix="fabric-bootstrap-trace-") as scratch:
        work = Path(scratch)
        build_probe(args.jdk, loader, work)
        lines = run_server(args.jdk, server_jar, libs, work / "run", args.timeout)
    classes = bootstrap_classes(lines, server_jar)
    if not classes:
        raise SystemExit("no game class loaded before the probe entrypoint: the trace did not see the game")
    header = HEADER + "".join(f"{line}\n" for line in manifest)
    args.output.write_text(header + "".join(f"{name}\n" for name in classes), encoding="utf-8")
    print(f"{len(classes)} classes -> {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
